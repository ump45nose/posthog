import { MakeLogicType, actions, afterMount, kea, key, listeners, path, props, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { lemonToast } from 'lib/lemon-ui/LemonToast'
import { organizationLogic } from 'scenes/organizationLogic'

import {
    crossProjectDashboardsPartialUpdate,
    crossProjectDashboardsRetrieve,
    crossProjectDashboardsTilesDestroy,
} from './generated/api'
import type { CrossProjectDashboardApi } from './generated/api.schemas'
import type { CrossProjectDashboardTileApi } from './generated/api.schemas'

export interface CrossProjectDashboardLogicProps {
    id: string
}

export interface CrossProjectDashboardFilters {
    date_from?: string | null
    date_to?: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface crossProjectDashboardLogicValues {
    dashboard: CrossProjectDashboardApi | null
    dashboardLoading: boolean
    projectIds: number[]
    tiles: readonly CrossProjectDashboardTileApi[]
    dashboardFilters: CrossProjectDashboardFilters
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface crossProjectDashboardLogicActions {
    loadDashboard: () => {
        value: true
    }
    loadDashboardFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadDashboardSuccess: (
        dashboard: CrossProjectDashboardApi | null,
        payload?: {
            value: true
        }
    ) => {
        dashboard: CrossProjectDashboardApi | null
        payload?: {
            value: true
        }
    }
    removeTile: (tileId: string) => {
        tileId: string
    }
    setDates: (
        dateFrom: string | null,
        dateTo: string | null
    ) => {
        dateFrom: string | null
        dateTo: string | null
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface crossProjectDashboardLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        tiles: (dashboard: CrossProjectDashboardApi | null) => readonly CrossProjectDashboardTileApi[]
        projectIds: (tiles: readonly CrossProjectDashboardTileApi[]) => number[]
        dashboardFilters: (dashboard: CrossProjectDashboardApi | null) => CrossProjectDashboardFilters
    }
}

export type crossProjectDashboardLogicType = MakeLogicType<
    crossProjectDashboardLogicValues,
    crossProjectDashboardLogicActions,
    CrossProjectDashboardLogicProps,
    crossProjectDashboardLogicMeta
>

export const crossProjectDashboardLogic = kea<crossProjectDashboardLogicType>([
    path((key) => ['products', 'cross_project_dashboards', 'frontend', 'crossProjectDashboardLogic', key]),
    props({} as CrossProjectDashboardLogicProps),
    key((props) => props.id),
    actions({
        loadDashboard: true,
        removeTile: (tileId: string) => ({ tileId }),
        setDates: (dateFrom: string | null, dateTo: string | null) => ({ dateFrom, dateTo }),
    }),
    loaders(({ props }) => ({
        dashboard: [
            null as CrossProjectDashboardApi | null,
            {
                loadDashboard: async () => {
                    const organizationId = organizationLogic.values.currentOrganization?.id
                    if (!organizationId) {
                        return null
                    }
                    return await crossProjectDashboardsRetrieve(organizationId, props.id)
                },
            },
        ],
    })),
    selectors({
        tiles: [(s) => [s.dashboard], (dashboard: CrossProjectDashboardApi | null) => dashboard?.tiles ?? []],
        projectIds: [
            (s) => [s.tiles],
            (tiles: CrossProjectDashboardTileApi[]) => Array.from(new Set(tiles.map((tile) => tile.project_id))),
        ],
        dashboardFilters: [
            (s) => [s.dashboard],
            (dashboard: CrossProjectDashboardApi | null) =>
                ((dashboard?.filters as CrossProjectDashboardFilters | undefined) ??
                    {}) as CrossProjectDashboardFilters,
        ],
    }),
    listeners(({ props, actions, values }) => ({
        setDates: async ({ dateFrom, dateTo }) => {
            const organizationId = organizationLogic.values.currentOrganization?.id
            if (!organizationId) {
                return
            }
            const filters: CrossProjectDashboardFilters = { ...values.dashboardFilters }
            // An unset bound is dropped, so the stored blob carries only the bounds actually chosen
            // and each tile keeps its own insight's value for the other one.
            dateFrom ? (filters.date_from = dateFrom) : delete filters.date_from
            dateTo ? (filters.date_to = dateTo) : delete filters.date_to
            try {
                await crossProjectDashboardsPartialUpdate(organizationId, props.id, { filters })
            } catch (error: any) {
                lemonToast.error(error?.detail || 'Could not apply that date range. Try again.')
            }
            actions.loadDashboard()
        },
        removeTile: async ({ tileId }) => {
            const organizationId = organizationLogic.values.currentOrganization?.id
            if (!organizationId) {
                return
            }
            try {
                await crossProjectDashboardsTilesDestroy(organizationId, props.id, tileId)
            } catch (error: any) {
                lemonToast.error(error?.detail || 'Could not remove that tile. Try again.')
            }
            actions.loadDashboard()
        },
    })),
    afterMount(({ actions }) => {
        actions.loadDashboard()
    }),
])
